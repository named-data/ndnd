func compileFromFileName(t *testing.T, fileName string) []byte {
	reader, err := os.Open(fileName)
	require.NoError(t, err)

	defer reader.Close()

	parser := lvs.NewParser(reader)
	lvsFile, err := parser.Parse()
	require.NoError(t, err)

	compiler := lvs.NewCompiler(lvsFile)
	model := compiler.Compile()

	return model.Bytes()
}

func compileFromString(t *testing.T, schema string) []byte {
	reader := strings.NewReader(schema)

	parser := lvs.NewParser(reader)
	lvsFile, err := parser.Parse()
	require.NoError(t, err)

	compiler := lvs.NewCompiler(lvsFile)
	model := compiler.Compile()

	return model.Bytes()
}

func TestCompileSimple(t *testing.T) {
	simpleTlv := compileFromString(t, `
#site: "a"/"blog"
#root: #site/#KEY
#article: #site/"article"/category/year/month <= #author
#author: #site/role/author/#KEY & { role: "author" } <= #admin
#admin: #site/"admin"/admin/#KEY <= #root
#KEY: "KEY"/_/_/_
	`)

	require.True(t, bytes.Equal(simpleTlv, SIMPLE_TEST))
}

func TestCompileComplex(t *testing.T) {
	complexTlv := compileFromString(t, `
#r1: a/b/c & { c: b, c: a, a: "a"|"x" } | { b: "b"|"y" } <= #r2 | #r3
// Not traililng
#r2: x/y/z & { x: "xxx" } // trailling!
#r3: x/y/z & { y: "yyy" }
`)

	require.True(t, bytes.Equal(complexTlv, COMPLEX_TEST))
}

func TestCompileOwnly(t *testing.T) {
	ownlyTlv := compileFromFileName(t, "lvs_test_ownly.trust")

	require.True(t, bytes.Equal(ownlyTlv, OWNLY_TEST))
}

func TestCompileConstraints(t *testing.T) {
	constraintsTlv := compileFromString(t, `
#key: "key"
#data: a/b & { b: $eq(a), a: "can" } | { a: $eq(b), b: "other" } <= #key
`)

	require.True(t, bytes.Equal(constraintsTlv, CONSTRAINTS_TEST))
}
